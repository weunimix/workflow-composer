// - 5 段契约全部覆盖
// - extends WorkflowBase 共享不确定性声明硬约束
// - 步骤子说明走 getStepDetail() 钩子
//
// 与原 .md 的差异：
// - frontmatter 改 prompt template 协议（name / description / argument-hint）
// - 4 硬约束中 3 条 subagent 专属约束已删除（结构性差异）
// - 仅保留不确定性声明，由 WorkflowBase.HARD_CONSTRAINTS 注入
// - 步骤子说明从「执行步骤」段拆出，进 getStepDetail()

import { WorkflowBase } from '../lib/workflows/workflow-base'
import { description } from '../lib/decorators/description'
import { config } from '../lib/decorators/config'
import { agentName } from '../lib/decorators/agent-name'
import { argumentHint } from '../lib/decorators/argument-hint'

@agentName('故事模拟')
@argumentHint('[角色] [场景]')
@description('基于角色和场景，通过三层信息预处理确保角色约束准确，在给定条件下模拟叙事推演')
@config({
  tools: 'read, subagent',
  context: 'fork',
  systemPromptMode: 'replace',
  inheritProjectContext: 'true',
  inheritSkills: 'true'
})
export class StorySimulationWorkflow extends WorkflowBase {
  public summary(): string {
    return `## 核心任务

接收角色和场景定义 → 条件完备性检查（6维度）→ 信息层1：session提取(fork) →
信息层2：system扫描(fresh) → 父会话编译信息包 → 信息层3：角色扮演(fresh) →
父会话审查 → 输出模拟报告。

核心理念：模拟的目的不是产出正式情节，而是探索性推演——暴露"我们对哪些条件
尚不确定"，引导后续设定补充工作。

${this.HARD_CONSTRAINTS}

## 用户输入预处理

当用户输入是长段描述时，先提取以下要素，整理展示后等待用户确认：

\`\`\`
## 模拟前整理

**角色定义**：
- 角色名：{名称}
- 核心特征：{性格、能力、立场、动机}
- 当前状态：{处境、知识、情绪}
- 信息来源：{从哪些文件/设定中提取}

**场景定义**：
- 时间/地点：{时空坐标}
- 场景要素：{关键实体——人物、物件、环境}
- 触发事件：{什么启动了模拟}

**已知条件**：
- {条件1}：{来源}

**模拟目标**：{用户想了解什么}
**模拟边界**：{不在本次模拟范围内的内容}
\`\`\`

简洁指令可跳过此步。`
  }

  public shouldDo(): string[] {
    return [
      '信息层1用 fork 上下文——能访问会话中的设定讨论',
      '信息层2用 fresh 上下文——独立扫描项目文档',
      '信息层1和2均遵守 4 条统一约束：仅输出角色可知信息、区分客观与主观、不输出其他角色主观信息、剔除剧透',
      '父会话编译信息包要做 4 步：合并、矛盾检测、去重、交付',
      '信息层3以叙事文本形式输出（非分析报告）',
      '每个基于缺失条件的推论标注 ⚠️ 基于缺失条件: {条件名}',
      '信息包有矛盾标注时标注 ⚠️ 信息矛盾: {描述}',
      '在自然叙事节点停止（决定做出/对话结束/事件节点完成）'
    ]
  }

  public shouldNot(): string[] {
    return [
      '模拟中"纠正"角色基于错误认知的行动',
      '信息层3输出其他角色的主观信息（内心状态、隐藏动机、秘密）',
      '因叙事需要让角色行为突然转变',
      '修改 subagent 输出——审查发现以注释形式附加在模拟文本后',
      '跳过父会话审查直接输出报告'
    ]
  }

  public watchOut(): string[] {
    return [
      '信息层1和2文档范围有差异：信息层2扫描项目文档时排除模板/格式规范/日志',
      '父会话审查 6 项：不确定性标注 / 信息边界 / 错误认知 / 行为一致性 / 世界规则 / 叙事终点',
      '条件完备性检查为建议性闸门——不阻塞但必须输出检查结果',
      '模拟目的是探索性推演，不是产出正式情节'
    ]
  }

  public getSteps(): string[] {
    return [
      '条件完备性检查',
      '信息层 1 — session 提取',
      '信息层 2 — system 扫描',
      '父会话编译信息包',
      '信息层 3 — 角色扮演',
      '父会话审查',
      '输出模拟报告'
    ]
  }

  protected override getStepDetail(stepName: string): string {
    const details: Record<string, string> = {
      '条件完备性检查': `在执行模拟前，对已知条件做完备性检查。只读分析，不修改文件。

| 维度 | 检查内容 | 缺失时的影响 |
|------|------|------|
| 角色知识 | 角色在此刻知道什么、不知道什么 | 行为可能超出信息边界 |
| 角色动机 | 核心驱动力是什么 | 行为缺乏方向 |
| 世界规则 | 场景涉及的自然/社会规则是否已确立 | 可能违反世界一致性 |
| 场景约束 | 空间、时间、资源、在场者 | 行为超出场景可能性 |
| 前因 | 前置事件链是否清晰 | 反应缺乏因果锚点 |
| 他人行为 | 其他角色的行为逻辑是否可推导 | 他人变成随机NPC |

输出检查结果后等待用户决定。此为建议性闸门，不阻塞。`,
      '信息层 1 — session 提取': `配置：agent: delegate, context: fork

从父会话完整对话历史中提取扮演所需信息。fork 上下文确保能访问会话中的设定讨论。

统一约束（信息层1和2共享）：
| # | 约束 |
|---|------|
| 1 | 仅输出角色当前可知道的信息——角色尚未经历/获知的事件不可输出 |
| 2 | 区分客观信息与主观信息 |
| 3 | 不得输出其他角色的主观信息（内心状态、隐藏动机、秘密） |
| 4 | 剔除剧透——未来真相、未揭示设定均不可输出 |

输出格式：统一信息格式（见输出格式段）。`,
      '信息层 2 — system 扫描': `配置：agent: delegate, context: fresh

从项目文档中提取扮演所需信息。fresh 上下文确保独立扫描。

文档范围：设定系统/、故事灵感库/、人物库/、时间线系统/、大纲/、创作宪法/
排除：模板文件、格式规范、日志

约束与信息层1完全一致。输出格式相同。`,
      '父会话编译信息包': `接收两层输出后：
1. 合并：按统一信息格式合并——同一字段存在两份来源时标注双重来源
2. 矛盾检测：检查矛盾（如会话中说情绪A，文档中描述为B）→ 标注在信息包中
3. 去重：相同信息合并，保留最完整来源
4. 交付：编译后作为扮演 subagent 的任务输入`,
      '信息层 3 — 角色扮演': `配置：agent: delegate, context: fresh

任务文本必须包含：
- 角色当前状态（知识、动机、情绪、位置）
- 角色行为模式（类似情境下的反应）
- 角色限制（不会做的事）
- 角色间关系认知（对场景中每个相关者的态度和信任程度）
- 角色自我认知（包括对自己的误解和错误认知）

模拟约束：
- 信息边界：严格基于"角色知道什么"行动
- 错误认知：角色基于错误认知行动是正常的——不要"纠正"
- 行为一致性：不得因叙事需要突然转变
- 视角约束：严格从角色有限视角出发

要求：
- 以叙事文本形式输出（非分析报告）
- 标注关键行为选择的推理依据
- 每个基于缺失条件的推论标注 ⚠️ 基于缺失条件: {条件名}
- 信息包有矛盾标注时标注 ⚠️ 信息矛盾: {描述}
- 在自然叙事节点停止（决定做出/对话结束/事件节点完成）`,
      '父会话审查': `| 审查项 | 检查内容 |
|------|------|
| 不确定性标注 | 每个基于缺失条件的推论是否标注了来源？ |
| 信息边界 | 角色是否做出了超出其信息边界的反应？ |
| 错误认知 | 角色基于错误认知的行动是否被"纠正"了（不应纠正）？ |
| 行为一致性 | 角色行为是否与其已确立特征矛盾？ |
| 世界规则 | 模拟是否违反已确立的世界规则？ |
| 叙事终点 | 模拟是否在自然节点停止？ |

审查发现以注释形式附加在模拟文本后，不直接修改 subagent 输出。`,
      '输出模拟报告': `按输出格式生成最终报告。`
    }
    return details[stepName] ?? ''
  }

  public buildOutput(): string {
    return `## 执行步骤

### 1. 条件完备性检查

${this.getStepDetail('条件完备性检查')}

### 2. 信息层 1 — session 提取

${this.getStepDetail('信息层 1 — session 提取')}

### 3. 信息层 2 — system 扫描

${this.getStepDetail('信息层 2 — system 扫描')}

### 4. 父会话编译信息包

${this.getStepDetail('父会话编译信息包')}

### 5. 信息层 3 — 角色扮演

${this.getStepDetail('信息层 3 — 角色扮演')}

### 6. 父会话审查

${this.getStepDetail('父会话审查')}

### 7. 输出模拟报告

${this.getStepDetail('输出模拟报告')}

## 输出格式

## 模拟配置
| 配置项 | 内容 |
|------|------|
| 角色 | {角色名} |
| 场景 | {时间/地点} |
| 触发事件 | {事件描述} |
| 条件完备度 | {高/中/低} |

## 条件完备性摘要
{步骤1检查结果——列出 ⚠️ 和 ❌ 项}

## 模拟
{扮演 subagent 的叙事文本原文}

## 审查注释

### 不确定性来源
| # | 缺失条件 | 对叙事的影响 | 位置 |
|---|------|------|------|

### 信息矛盾（如有）
| # | 矛盾点 | 信息层1 | 信息层2 | 对叙事的影响 |

### 信息边界检查
{角色是否超出信息边界？}

### 错误认知检查
{角色基于错误认知的行动是否被"纠正"了？}

### 行为一致性检查
{角色行为是否与已确立特征矛盾？}

---

## 附录A：统一信息格式

### 客观信息（任意角色可感知的环境与事实）
- 场景环境（时间/地点/物理环境）
- 世界规则（与本场景相关的已确立规则）
- 已知事件（本时间点之前已发生的、角色可能知晓的事件）
- 角色社会处境（制度位置、社会关系、社会约束）

### 主观信息（仅本角色可感知）
- 角色状态（当前知识、情绪、动机）
- 角色特征（能力/限制、行为模式、价值优先级）
- 角色间关系认知（对每个场景相关者的已知信息、态度、信任程度）
- 角色自我认知（对自己的了解、对自己的误解）
- 角色已知的错误认知

### 信息边界（角色不知道什么）
| # | 角色不知道的内容 | 原因 | 来源 |
|---|---------------|------|------|`
  }
}
